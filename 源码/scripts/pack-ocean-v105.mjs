import {PNG} from 'pngjs';
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {createHash,randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';

const root='../素材/游戏美术',out=root+'/slices/v105';mkdirSync(out,{recursive:true});
const sha=b=>createHash('sha256').update(b).digest('hex');
const specs=[
  ['predator-fish',[
    ['fish.predator.swim.0',[0,0,600,420]],['fish.predator.swim.1',[600,0,654,420]],
    ['fish.predator.tell',[0,420,520,410]],['fish.predator.dash',[520,420,734,410]],
    ['fish.predator.recover',[0,830,595,424]],['fish.predator.defeat',[595,830,659,424]],
  ]],
  ['sonar-swim',Array.from({length:4},(_,i)=>[
    `diver.sonar.swim.${i}`,[i%2*768,Math.floor(i/2)*512,768,512],
    [450+i%2*768,310+Math.floor(i/2)*512],[663+i%2*768,307+Math.floor(i/2)*512]
  ])]
];
const frames={},regions={},poses=[],records=[];
const atlas=new PNG({width:2048,height:1024});let px=8,py=8,rowH=0;
for(const [name,items] of specs){
 const source=`${root}/source/v105/${name}.png`,bytes=readFileSync(source),p=PNG.sync.read(bytes);
 for(const [id,cell,pivot,muzzle] of items){
  const [cx,cy,cw,ch]=cell;let l=cx+cw,t=cy+ch,r=cx,b=cy,solid=0;
  for(let y=cy;y<Math.min(p.height,cy+ch);y++)for(let x=cx;x<Math.min(p.width,cx+cw);x++){
   if(p.data[(y*p.width+x)*4+3]>24){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);solid++;}
  }
  assert.ok(solid>1000,id);assert.ok(l>cx+2&&r<cx+cw-2&&t>cy+2&&b<cy+ch-2,`${id}: clipped cell ${[l,t,r,b]}`);
  l-=3;t-=3;r+=3;b+=3;const w=r-l+1,h=b-t+1;
  const slice=new PNG({width:w,height:h});PNG.bitblt(p,slice,l,t,w,h,0,0);
  const sliceBytes=PNG.sync.write(slice);writeFileSync(`${out}/${id}.png`,sliceBytes);
  // Deterministic premultiplied-alpha 2x box filter. Preserve the untouched crop separately.
  const rw=Math.ceil(w/2),rh=Math.ceil(h/2),runtime=new PNG({width:rw,height:rh});
  for(let y=0;y<rh;y++)for(let x=0;x<rw;x++){
   let a=0,n=0,rr=0,g=0,bb=0;
   for(let dy=0;dy<2;dy++)for(let dx=0;dx<2;dx++){
    const sx=x*2+dx,sy=y*2+dy;if(sx>=w||sy>=h)continue;
    const j=(sy*w+sx)*4,alpha=slice.data[j+3];a+=alpha;rr+=slice.data[j]*alpha;g+=slice.data[j+1]*alpha;bb+=slice.data[j+2]*alpha;n++;
   }
   const j=(y*rw+x)*4;runtime.data[j]=a?Math.round(rr/a):0;runtime.data[j+1]=a?Math.round(g/a):0;
   runtime.data[j+2]=a?Math.round(bb/a):0;runtime.data[j+3]=Math.round(a/n);
  }
  if(px+rw+8>atlas.width){px=8;py+=rowH+16;rowH=0;}
  assert.ok(py+rh+8<=atlas.height);PNG.bitblt(runtime,atlas,0,0,rw,rh,px,py);
  regions[id]=[px,py,rw,rh];px+=rw+16;rowH=Math.max(rowH,rh);
  frames[id]={file:'ocean-v105',size:[rw,rh],sourceSize:[w,h],source:`../素材/游戏美术/slices/v105/${id}.png`,sha256:sha(sliceBytes)};
  if(pivot)poses.push({frame:id,size:[w,h],pivot:[pivot[0]-l,pivot[1]-t],muzzle:[muzzle[0]-l,muzzle[1]-t],scale:.145});
  records.push({id,source,sourceSHA256:sha(bytes),sourceSize:[p.width,p.height],cell,crop:[l,t,w,h],runtimeSize:[rw,rh],atlas:regions[id],sliceSHA256:sha(sliceBytes)});
 }
}
const atlasBytes=PNG.sync.write(atlas);writeFileSync('assets/level02/ocean-v105.png',atlasBytes);
const metaPath='assets/level02/ocean-v105.png.meta';
if(!existsSync(metaPath)){
 const m=JSON.parse(readFileSync('assets/level02/combat-v0818.png.meta','utf8')),uuid=randomUUID(),previous=m.uuid;
 writeFileSync(metaPath,JSON.stringify(JSON.parse(JSON.stringify(m).replaceAll(previous,uuid).replaceAll('combat-v0818','ocean-v105')),null,2)+'\n');
}
writeFileSync('assets/scripts/ocean/OceanUpdateFrames.ts',`// Generated by scripts/pack-ocean-v105.mjs from preserved imagegen originals.\nexport const OceanUpdateFrames = ${JSON.stringify(frames,null,2)};\nexport const OceanUpdateRegions: Record<string, readonly [number,number,number,number]> = ${JSON.stringify(regions,null,2)};\nexport const SonarMotionPoses = ${JSON.stringify(poses,null,2)} as const;\n`);
writeFileSync(`${root}/v105-manifest.json`,JSON.stringify({tool:'image_gen.imagegen',atlas:'源码/assets/level02/ocean-v105.png',atlasSHA256:sha(atlasBytes),processing:'Original RGBA crops preserved; runtime uses 2x premultiplied-alpha box downsampling, 16 px transparent gaps, no painted content edits.',records},null,2)+'\n');
console.log(JSON.stringify({frames:records.length,atlasSHA256:sha(atlasBytes),records:records.map(r=>({id:r.id,crop:r.crop}))},null,2));
