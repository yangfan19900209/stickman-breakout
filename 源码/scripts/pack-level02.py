"""Build chapter bundle from preserved source crops. Runtime resize is explicit, originals untouched."""
import json, hashlib, uuid, wave, math, struct, random
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
out=ROOT/'assets/level02'
out.mkdir(parents=True,exist_ok=True)
manifest=json.loads((ROOT/'../素材/游戏美术/level02-manifest.json').read_text(encoding='utf8'))
frames={}
for f in manifest['frames']:
    if f['usage']=='design-reference':continue
    path=ROOT/f['file']
    im=Image.open(path).convert('RGBA')
    # Keep actor originals sharp; chapter backgrounds are downsampled to 1280 wide.
    if f['id'].startswith('background.'):
        im=im.resize((1280,round(im.height*1280/im.width)),Image.Resampling.LANCZOS)
        dest=out/(f['id']+'.jpg');im.convert('RGB').save(dest,quality=88)
    else:
        factor=1 if f['id'].startswith(('submarine.','terrain.')) else .5
        im=im.resize((max(1,round(im.width*factor)),max(1,round(im.height*factor))),Image.Resampling.LANCZOS)
        dest=out/(f['id']+'.png');im.quantize(colors=128,method=Image.Quantize.FASTOCTREE).save(dest,optimize=True)
    frames[f['id']]={'file':dest.stem,'size':list(im.size),'sourceSize':f['size'],'source':f['file'],'sha256':hashlib.sha256(dest.read_bytes()).hexdigest()}
bundleMeta={'ver':'1.2.0','importer':'directory','imported':True,'uuid':str(uuid.uuid5(uuid.NAMESPACE_URL,'stickman/level02')),'files':[],'subMetas':{},'userData':{'isBundle':True,'bundleName':'level02','bundleConfigID':'chapter-local','priority':1}}
(ROOT/'assets/level02.meta').write_text(json.dumps(bundleMeta,indent=2),encoding='utf8')
(ROOT/'assets/scripts/ocean/OceanFrames.ts').write_text('import { OceanStyleFrames } from "./OceanStyleFrames";\nimport { OceanMotionFrames } from "./OceanMotionFrames";\nimport { OceanDetailFrames } from "./OceanDetailFrames";\n// Generated by scripts/pack-level02.py. Native region sizes retained for common scales.\nexport const OceanFrames:Record<string,{file:string;size:number[];sourceSize:number[];source:string;sha256:string}>= '+json.dumps(frames,ensure_ascii=False,separators=(',',':'))+';\nObject.assign(OceanFrames, OceanDetailFrames, OceanMotionFrames, OceanStyleFrames);\n',encoding='utf8')
(ROOT/'../素材/游戏美术/level02-runtime.json').write_text(json.dumps({'bundle':'level02','processing':'Runtime PNGs: submarine hull and terrain retain dimensions; other sprites resized to 50 percent; all quantized to 128 colors (lossy). Background JPG 1280 wide quality 88. Source PNGs retained unchanged.','frames':frames},ensure_ascii=False,indent=2),encoding='utf8')
for name,duration in [('sonar',.24),('water-blast',.65)]:
    rng=random.Random(27);samples=[];rate=22050
    for i in range(round(rate*duration)):
        t=i/rate;env=math.sin(math.pi*min(1,t/.012)/2)*math.exp(-t/(duration*.28))
        value=(math.sin(2*math.pi*(620*t-650*t*t))*.65+math.sin(2*math.pi*310*t)*.15) if name=='sonar' else (math.sin(2*math.pi*72*t)*.6+rng.uniform(-1,1)*.25)
        samples.append(struct.pack('<h',round(value*env*18000)))
    with wave.open(str(out/(name+'.wav')),'wb') as audio:
        audio.setparams((1,2,rate,0,'NONE','not compressed'));audio.writeframes(b''.join(samples))
print('Prepared',len(frames),'chapter resources;',sum(p.stat().st_size for p in out.iterdir() if p.suffix in ['.png','.jpg']),'bytes')

