from os.path import relpath
"""Pack whole rifle poses; preserve source RGBA crops and measured muzzle/foot sockets."""
from pathlib import Path
import hashlib, json, math
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'../素材/游戏美术/source/v071/rifle-actions.png'
OUT=ROOT/'../素材/游戏美术/slices/v071';OUT.mkdir(parents=True,exist_ok=True)
sheet=Image.open(SOURCE).convert('RGBA')
assert sheet.size==(1448,1086), 'Re-measure pivots and muzzles for a different source.'
SCALE=.30
# Native source pixels, virtual foot pivot and visible muzzle center.
poses=[
 ('jump.0',0,0,(193,337),(320,176)),('jump.1',1,0,(553,337),(674,176)),
 ('fall.0',2,0,(909,337),(1031,184)),('fall.1',3,0,(1265,337),(1389,181)),
 ('up-stand',0,1,(181,694),(227,403)),('up-crouch',1,1,(537,694),(594,443)),
 ('up-jump',2,1,(899,694),(947,403)),('up-fall',3,1,(1262,694),(1307,403)),
 ('diagonal-stand',0,2,(187,1041),(291,816)),('diagonal-crouch',1,2,(540,1041),(633,842)),
 ('diagonal-jump',2,2,(903,1056),(1008,799)),('diagonal-fall',3,2,(1267,1060),(1368,807)),
]
frames={};sockets={};entries=[];atlas=Image.new('RGBA',(1024,512));x=y=4;rowh=0
for name,c,r,pivot,muzzle in poses:
 cell=(c*362,r*362,(c+1)*362,(r+1)*362)
 b=sheet.crop(cell).getchannel('A').point(lambda a:255 if a>=16 else 0).getbbox()
 assert b
 crop=(max(cell[0],(cell[0]+b[0]-4)//2*2),max(cell[1],(cell[1]+b[1]-4)//2*2),min(cell[2],math.ceil((cell[0]+b[2]+4)/2)*2),min(cell[3],math.ceil((cell[1]+b[3]+4)/2)*2))
 original=sheet.crop(crop);id='direct.rifle.'+name;file=OUT/(id+'.png');original.save(file,optimize=True)
 image=original.resize((original.width//2,original.height//2),Image.Resampling.LANCZOS)
 if x+image.width+4>atlas.width:x,y,rowh=4,y+rowh+8,0
 assert y+image.height+4<=atlas.height
 atlas.paste(image,(x,y))
 anchor=[(pivot[0]-crop[0])/original.width,1-(pivot[1]-crop[1])/original.height]
 frames[id]={'atlas':[x,y,*image.size],'anchor':anchor,'sourceSize':list(original.size),'size':list(image.size)}
 sockets[id]=[(muzzle[0]-pivot[0])*SCALE,(pivot[1]-muzzle[1])*SCALE]
 entries.append({'id':id,'file':Path(relpath(file, ROOT)).as_posix(),'sha256':hashlib.sha256(file.read_bytes()).hexdigest(),'crop':crop,'pivotSource':pivot,'muzzleSource':muzzle,**frames[id]})
 x+=image.width+8;rowh=max(rowh,image.height)
runtime=ROOT/'assets/resources/comic/rifle-actions.png'
atlas.quantize(colors=32,method=Image.Quantize.FASTOCTREE).save(runtime,optimize=True)
text='// Generated by scripts/prepare-rifle-actions.py; whole bodies, no gun-removal masks.\n'
for name,value in [('RifleActionFrames',frames),('RifleActionSockets',sockets)]:text+='export const '+name+' = '+json.dumps(value,separators=(',',':'))+' as const;\n'
text+='export const RifleActionScale = .30;\n'
(ROOT/'assets/scripts/render/RifleActionFrames.ts').write_text(text,encoding='utf8')
manifest={'source':{'file':Path(relpath(SOURCE, ROOT)).as_posix(),'size':list(sheet.size),'sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest()},'runtime':{'file':Path(relpath(runtime, ROOT)).as_posix(),'size':list(atlas.size),'bytes':runtime.stat().st_size,'sha256':hashlib.sha256(runtime.read_bytes()).hexdigest()},'processing':'Original RGBA source and whole-body crops retained. Runtime uniform half-resolution, 32-color quantization (lossy). Transparent gutters retained.','worldScale':SCALE,'frames':entries}
(ROOT/'../素材/游戏美术/v071-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf8')
print(json.dumps({'frames':len(entries),'bytes':runtime.stat().st_size}))
