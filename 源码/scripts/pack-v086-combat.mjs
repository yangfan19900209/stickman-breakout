import { PNG } from "pngjs";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
// Crop/resample generated RGBA only. No painted geometry or recoloring.
const atlas = new PNG({ width: 2048, height: 512 }),
  frames = {},
  regions = {},
  poses = {},
  records = [];
let ax = 4,
  ay = 4,
  rh = 0;
const sha = (b) => createHash("sha256").update(b).digest("hex");
for (const [file, cols, rows, scale] of [
  ["enemy-loadouts", 4, 3, 0.7],
  ["projectiles", 3, 2, 0.35],
  ["harpoon-darts", 1, 2, 0.12],
]) {
  const bytes = readFileSync(`../素材/游戏美术/source/v086/${file}.png`),
    p = PNG.sync.read(bytes);
  for (let row = 0; row < rows; row++)
    for (let col = 0; col < cols; col++) {
      if (file === "projectiles" && col === 0) continue; // Discard generic arrow candidates; select the generated physical darts instead.
      const xs =
        file === "enemy-loadouts"
          ? [0, 350, 730, 1090, p.width]
          : file === "projectiles"
            ? [0, 535, 968, p.width]
            : [0, p.width];
      const ys =
        file === "enemy-loadouts"
          ? [0, 365, 725, p.height]
          : [0, p.height / 2, p.height];
      const cell = [xs[col], ys[row], xs[col + 1], ys[row + 1]];
      let l = cell[2],
        t = cell[3],
        r = cell[0],
        b = cell[1],
        pixels = 0,
        opaqueWhite = 0;
      for (let y = cell[1]; y < cell[3]; y++)
        for (let x = cell[0]; x < cell[2]; x++) {
          const i = (y * p.width + x) * 4;
          if (p.data[i + 3] < 8) continue;
          l = Math.min(l, x);
          r = Math.max(r, x);
          t = Math.min(t, y);
          b = Math.max(b, y);
          pixels++;
          if (p.data[i] > 220 && p.data[i + 3] > 245) opaqueWhite++;
        }
      if (
        pixels < 500 ||
        opaqueWhite < 300 ||
        l <= cell[0] ||
        r >= cell[2] - 1 ||
        t <= cell[1] ||
        b >= cell[3] - 1
      )
        throw Error("Clipped or empty sprite " + file + row + col);
      l -= 2;
      t -= 2;
      r += 2;
      b += 2;
      const sw = r - l + 1,
        sh = b - t + 1,
        w = Math.round(sw * scale),
        h = Math.round(sh * scale);
      if (ax + w + 4 > 2048) {
        ax = 4;
        ay += rh + 8;
        rh = 0;
      }
      if (ay + h + 4 > 512) throw Error("Atlas overflow");
      for (let y = 0; y < h; y++)
        for (let x = 0; x < w; x++) {
          const xa = l + (x * sw) / w,
            xb = l + ((x + 1) * sw) / w,
            ya = t + (y * sh) / h,
            yb = t + ((y + 1) * sh) / h;
          let area = 0,
            alpha = 0,
            rgb = [0, 0, 0];
          for (let sy = Math.floor(ya); sy < Math.ceil(yb); sy++)
            for (let sx = Math.floor(xa); sx < Math.ceil(xb); sx++) {
              const a =
                  Math.max(0, Math.min(sx + 1, xb) - Math.max(sx, xa)) *
                  Math.max(0, Math.min(sy + 1, yb) - Math.max(sy, ya)),
                i = (sy * p.width + sx) * 4;
              area += a;
              alpha += a * p.data[i + 3];
              for (let k = 0; k < 3; k++)
                rgb[k] += a * p.data[i + 3] * p.data[i + k];
            }
          const out = ((ay + y) * 2048 + ax + x) * 4;
          for (let k = 0; k < 3; k++)
            atlas.data[out + k] = alpha ? Math.round(rgb[k] / alpha) : 0;
          atlas.data[out + 3] = Math.round(alpha / area);
        }
      const weapon =
        file === "harpoon-darts"
          ? "harpoon"
          : ["harpoon", "sonar", "torpedo"][
              file === "enemy-loadouts" ? row : col
            ];
      const id =
        file === "enemy-loadouts"
          ? `enemy.${weapon}.${["aim", "swim.0", "swim.1", "evade"][col]}`
          : `shot.${["player", "enemy"][row]}.${weapon}`;
      frames[id] = { file: "combat-v086", size: [w, h], sourceSize: [sw, sh] };
      regions[id] = [ax, ay, w, h];
      if (file === "enemy-loadouts") {
        const py = row * 362 + 176,
          px = [218, 568, 935, 1292][col],
          mx = [
            [113, 457, 821, 1180],
            [81, 419, 778, 1144],
            [68, 409, 767, 1133],
          ][row][col];
        poses[id] = {
          size: [sw, sh],
          pivot: [px - l, py - t],
          muzzle: [mx - l, py - t],
          scale: 0.235,
        };
      }
      records.push({
        id,
        source: file + ".png",
        sourceSHA256: sha(bytes),
        crop: [l, t, sw, sh],
        region: regions[id],
        opaqueWhite,
        pixels,
      });
      ax += w + 8;
      rh = Math.max(rh, h);
    }
}
const output = PNG.sync.write(atlas);
writeFileSync("assets/level02/combat-v086.png", output);
writeFileSync(
  "assets/scripts/ocean/OceanCombatFrames.ts",
  `// Generated by scripts/pack-v086-combat.mjs. Original sprite coordinates retained.\nexport const CombatFrames = ${JSON.stringify(frames, null, 2)};\nexport const CombatRegions:Record<string,[number,number,number,number]> = ${JSON.stringify(regions, null, 2)};\nexport const EnemyPoses:Record<string,{size:number[];pivot:number[];muzzle:number[];scale:number}> = ${JSON.stringify(poses, null, 2)};\n`,
);
mkdirSync("../开发进度/验证记录", { recursive: true });
writeFileSync(
  "../开发进度/验证记录/v086-art.json",
  JSON.stringify(
    {
      tool: "image_gen.imagegen",
      atlas: {
        path: "assets/level02/combat-v086.png",
        width: 2048,
        height: 512,
        bytes: output.length,
        sha256: sha(output),
      },
      records,
    },
    null,
    2,
  ),
);
console.log(
  JSON.stringify({
    frames: records.length,
    bytes: output.length,
    occupiedHeight: ay + rh,
  }),
);
