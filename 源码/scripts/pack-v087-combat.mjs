import { PNG } from "pngjs";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
// Only crop, premultiplied-alpha resample and pack generated art. No painted shapes.
const atlas = new PNG({ width: 2048, height: 512 }),
  frames = {},
  regions = {},
  poses = {},
  records = [];
let ax = 4,
  ay = 4,
  rh = 0;
const sha = (b) => createHash("sha256").update(b).digest("hex");
for (const [file, cols, scale] of [
  ["mini-submarine", 2, 0.55],
  ["harpoon-darts", 1, 0.18],
]) {
  const bytes = readFileSync(`../素材/游戏美术/source/v087/${file}.png`),
    p = PNG.sync.read(bytes);
  for (let row = 0; row < 2; row++)
    for (let col = 0; col < cols; col++) {
      const cell = [
        (col * p.width) / cols,
        (row * p.height) / 2,
        ((col + 1) * p.width) / cols,
        ((row + 1) * p.height) / 2,
      ];
      let l = cell[2],
        t = cell[3],
        r = cell[0],
        b = cell[1],
        pixels = 0,
        opaqueWhite = 0;
      for (let y = cell[1]; y < cell[3]; y++)
        for (let x = cell[0]; x < cell[2]; x++) {
          const i = (y * p.width + x) * 4;
          if (p.data[i + 3] < 8) continue;
          l = Math.min(l, x);
          r = Math.max(r, x);
          t = Math.min(t, y);
          b = Math.max(b, y);
          pixels++;
          if (p.data[i] > 220 && p.data[i + 3] > 245) opaqueWhite++;
        }
      if (
        pixels < 500 ||
        opaqueWhite < 300 ||
        l <= cell[0] + 2 ||
        r >= cell[2] - 3 ||
        t <= cell[1] + 2 ||
        b >= cell[3] - 3
      )
        throw Error("Clipped/empty " + file + row + col);
      l -= 2;
      t -= 2;
      r += 2;
      b += 2;
      const sw = r - l + 1,
        sh = b - t + 1,
        w = Math.round(sw * scale),
        h = Math.round(sh * scale);
      if (ax + w + 4 > 2048) {
        ax = 4;
        ay += rh + 8;
        rh = 0;
      }
      if (ay + h + 4 > 512) throw Error("Atlas overflow");
      for (let y = 0; y < h; y++)
        for (let x = 0; x < w; x++) {
          const xa = l + (x * sw) / w,
            xb = l + ((x + 1) * sw) / w,
            ya = t + (y * sh) / h,
            yb = t + ((y + 1) * sh) / h;
          let area = 0,
            alpha = 0,
            rgb = [0, 0, 0];
          for (let sy = Math.floor(ya); sy < Math.ceil(yb); sy++)
            for (let sx = Math.floor(xa); sx < Math.ceil(xb); sx++) {
              const a =
                  Math.max(0, Math.min(sx + 1, xb) - Math.max(sx, xa)) *
                  Math.max(0, Math.min(sy + 1, yb) - Math.max(sy, ya)),
                i = (sy * p.width + sx) * 4;
              area += a;
              alpha += a * p.data[i + 3];
              for (let k = 0; k < 3; k++)
                rgb[k] += a * p.data[i + 3] * p.data[i + k];
            }
          const out = ((ay + y) * 2048 + ax + x) * 4;
          for (let k = 0; k < 3; k++)
            atlas.data[out + k] = alpha ? Math.round(rgb[k] / alpha) : 0;
          atlas.data[out + 3] = Math.round(alpha / area);
        }
      const id =
        file === "mini-submarine"
          ? `minisub.${["intact.0", "intact.1", "damaged", "wreck"][row * 2 + col]}`
          : `shot.${row ? "enemy" : "player"}.harpoon`;
      frames[id] = { file: "combat-v087", size: [w, h], sourceSize: [sw, sh] };
      regions[id] = [ax, ay, w, h];
      if (file === "mini-submarine") {
        // Measured original-sheet pixels; all frames retain the same .28 world/source scale.
        const px = 390 + col * 744,
          py = 320 + row * 475;
        const sockets = [
          [78 + col * 745, 298 + row * 475],
          [115 + col * 749, 371 + row * 476],
          [115 + col * 749, 428 + row * 475],
        ];
        poses[id] = {
          size: [sw, sh],
          pivot: [px - l, py - t],
          sockets: sockets.map(([x, y]) => [x - l, y - t]),
        };
      }
      records.push({
        id,
        source: file + ".png",
        sourceSHA256: sha(bytes),
        crop: [l, t, sw, sh],
        region: regions[id],
        opaqueWhite,
        pixels,
      });
      ax += w + 8;
      rh = Math.max(rh, h);
    }
}
const output = PNG.sync.write(atlas);
writeFileSync("assets/level02/combat-v087.png", output);
writeFileSync(
  "assets/scripts/ocean/OceanMiniFrames.ts",
  `// Generated by scripts/pack-v087-combat.mjs; source-pixel anchors preserve scale.\nexport const MiniFrames=${JSON.stringify(frames, null, 2)};\nexport const MiniRegions:Record<string,[number,number,number,number]>=${JSON.stringify(regions, null, 2)};\nexport const MiniPoses:Record<string,{size:number[];pivot:number[];sockets:number[][]}>=${JSON.stringify(poses, null, 2)};\n`,
);
writeFileSync(
  "../开发进度/验证记录/v087-art.json",
  JSON.stringify(
    {
      tool: "image_gen.imagegen",
      atlas: {
        path: "assets/level02/combat-v087.png",
        width: 2048,
        height: 512,
        bytes: output.length,
        sha256: sha(output),
      },
      records,
    },
    null,
    2,
  ),
);
