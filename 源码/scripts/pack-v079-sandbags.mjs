import {PNG} from 'pngjs';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source='../素材/游戏美术/source/v079/sandbag-debris.png',input=PNG.sync.read(readFileSync(source));
const output=new PNG({width:320,height:176}),frames={},manifest=[];
for(let i=0;i<4;i++){
 const x0=(i%2)*input.width/2,y0=Math.floor(i/2)*input.height/2;
 let left=input.width,top=input.height,right=0,bottom=0;
 for(let y=y0;y<y0+input.height/2;y++)for(let x=x0;x<x0+input.width/2;x++){
  if(input.data[(y*input.width+x)*4+3]>8){left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);}
 }
 left=Math.max(x0,left-2);top=Math.max(y0,top-2);right+=2;bottom+=2;
 const width=Math.ceil((right-left+1)/4),height=Math.ceil((bottom-top+1)/4),dx=(i%2)*160+4,dy=Math.floor(i/2)*88+4;
 if(width>152||height>80)throw new Error('Generated sprite does not fit its padded slot');
 for(let y=0;y<height;y++)for(let x=0;x<width;x++){
  let alpha=0,r=0,g=0,b=0;
  for(let yy=0;yy<4;yy++)for(let xx=0;xx<4;xx++){
   const sx=left+x*4+xx,sy=top+y*4+yy;if(sx>right||sy>bottom||sx>=input.width||sy>=input.height)continue;
   const at=(sy*input.width+sx)*4,a=input.data[at+3];alpha+=a;r+=input.data[at]*a;g+=input.data[at+1]*a;b+=input.data[at+2]*a;
  }
  const dest=((dy+y)*output.width+dx+x)*4;
  output.data[dest]=alpha?r/alpha:0;output.data[dest+1]=alpha?g/alpha:0;output.data[dest+2]=alpha?b/alpha:0;output.data[dest+3]=alpha/16;
 }
 const id=`bag.debris.${i}`;frames[id]={atlas:[dx,dy,width,height],size:[width,height],sourceSize:[width,height],anchor:[.5,.5]};
 manifest.push({id,sourceCrop:[left,top,right-left+1,bottom-top+1],...frames[id]});
}
mkdirSync('assets/landart',{recursive:true});writeFileSync('assets/landart/sandbag-debris.png',PNG.sync.write(output));
writeFileSync('assets/scripts/render/SandbagFrames.ts','// Generated by scripts/pack-v079-sandbags.mjs; source alpha retained.\nexport const SandbagFrames = '+JSON.stringify(frames)+' as const;\n');
writeFileSync('../素材/游戏美术/v079-sandbag-manifest.json',JSON.stringify({source,sourceSHA256:createHash('sha256').update(readFileSync(source)).digest('hex'),runtime:'assets/landart/sandbag-debris.png',size:[320,176],downsample:'4x premultiplied-alpha box filter',frames:manifest},null,2));
console.log(JSON.stringify({size:[320,176],frames:manifest.map(f=>({id:f.id,size:f.size}))}));
