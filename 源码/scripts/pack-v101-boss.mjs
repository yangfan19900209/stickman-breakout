import { PNG } from 'pngjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

// Full generated poses only. Copy original RGBA without scaling/repainting.
// Keep the existing atlas resource identity so no extra texture enters the package.
const sha = b => createHash('sha256').update(b).digest('hex');
const specs = [
  { source:'../素材/游戏美术/source/v088/rhino.png', prefix:'rhino', rows:2,
    names:['idle','roll.0','roll.1','fire','ram-tell','ram','damaged','wreck'],
    pivots:[[245,391],[689,391],[1133,392],[1576,391],[245,836],[690,836],[1133,835],[1576,835]],
    sockets:[[79,221],[524,222],[968,226],[1447,228],[93,632],[500,693],[964,667],[1400,730]].map(muzzle=>({muzzle})) },
  { source:'../素材/游戏美术/source/v101/colossus.png', prefix:'colossus', rows:3,
    names:['idle','walk.0','walk.1','walk.2','walk.3','fire','stomp-tell','stomp','charge','damaged','collapse','wreck'],
    pivots:[[190,331],[548,332],[907,331],[1259,333],[178,678],[546,677],[902,677],[1269,677],[197,1022],[548,1022],[900,1022],[1263,1021]],
    sockets:[
      [[64,230],[183,210],[118,162],[264,162]],
      [[416,229],[539,207],[476,163],[620,163]],
      [[781,230],[888,207],[832,171],[974,164]],
      [[1133,226],[1244,212],[1186,165],[1329,165]],
      [[62,571],[170,554],[113,513],[252,506]],
      [[410,553],[540,546],[495,502],[635,530]],
      [[773,552],[890,549],[839,501],[983,511]],
      [[1129,591],[1249,585],[1186,543],[1326,540]],
      [[41,900],[195,904],[132,860],[286,865]],
      [[417,916],[539,902],[477,864],[621,870]],
      [[763,951],[881,932],[821,887],[962,877]],
      [[1114,994],[1235,973],[1164,936],[1306,899]],
    ].map(a=>Object.fromEntries(['muzzle','core','leftPod','rightPod'].map((key,i)=>[key,a[i]]))) },
];
const atlas = new PNG({width:2048,height:2048}), frames={}, sockets={}, records=[];
let ax=4,ay=4,rowH=0;
mkdirSync('../素材/游戏美术/slices/v101',{recursive:true});
for(const spec of specs){
  const bytes=readFileSync(spec.source),p=PNG.sync.read(bytes);
  for(let row=0;row<spec.rows;row++){
    const t=Math.floor(row*p.height/spec.rows),b=Math.floor((row+1)*p.height/spec.rows),runs=[];
    let start=-1;
    for(let x=0;x<=p.width;x++){
      let n=0;if(x<p.width)for(let y=t;y<b;y++)if(p.data[(y*p.width+x)*4+3]>20)n++;
      if(n>1){if(start<0)start=x;}else if(start>=0){if(x-start>40)runs.push([start,x]);start=-1;}
    }
    assert.equal(runs.length,4,`${spec.prefix} row ${row}: four separate full poses`);
    for(let col=0;col<4;col++){
      const n=row*4+col,id=`${spec.prefix}.${spec.names[n]}`,[lo,hi]=runs[col];
      let left=hi,right=lo,top=b,bottom=t,opaqueWhite=0,pixels=0;
      for(let y=t;y<b;y++)for(let x=lo;x<hi;x++){
        const i=(y*p.width+x)*4;if(p.data[i+3]<=20)continue;
        left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);pixels++;
        if(p.data[i]>220&&p.data[i+1]>220&&p.data[i+2]>220&&p.data[i+3]>245)opaqueWhite++;
      }
      assert.ok(pixels>1000&&opaqueWhite>500,id);
      const crop=[Math.max(0,left-3),Math.max(t,top-3),Math.min(p.width,right+4),Math.min(b,bottom+4)];
      const [l,ct,r,cb]=crop,w=r-l,h=cb-ct,slice=new PNG({width:w,height:h}),pivot=spec.pivots[n];
      if(ax+w+4>atlas.width){ax=4;ay+=rowH+8;rowH=0;}
      assert.ok(ay+h+4<=atlas.height,'atlas overflow');
      for(let y=0;y<h;y++){
        p.data.copy(slice.data,y*w*4,((ct+y)*p.width+l)*4,((ct+y)*p.width+r)*4);
        slice.data.copy(atlas.data,((ay+y)*atlas.width+ax)*4,y*w*4,(y+1)*w*4);
      }
      const size=[w,h],anchor=[(pivot[0]-l)/w,1-(pivot[1]-ct)/h];
      frames[id]={atlas:[ax,ay,w,h],size,sourceSize:size,anchor};
      sockets[id]=Object.fromEntries(Object.entries(spec.sockets[n]).map(([key,[x,y]])=>[key,[x-pivot[0],pivot[1]-y]]));
      records.push({id,source:spec.source,sourceSHA256:sha(bytes),sourceSize:[p.width,p.height],crop,region:frames[id].atlas,pivot,sockets:spec.sockets[n],opaqueWhite,pixels,pixelSHA256:sha(slice.data)});
      if(spec.prefix==='colossus')writeFileSync(`../素材/游戏美术/slices/v101/${id}.png`,PNG.sync.write(slice));
      ax+=w+8;rowH=Math.max(rowH,h);
    }
  }
}
const bytes=PNG.sync.write(atlas,{deflateLevel:9});
writeFileSync('assets/landart/boss-v088.png',bytes);
writeFileSync('assets/scripts/render/BossFrames.ts',`// Generated by scripts/pack-v101-boss.mjs. V101 redrawn compact colossus; V088 rhino pixels unchanged.\nexport const BossFrames=${JSON.stringify(frames,null,2)} as const;\nexport const BossSockets=${JSON.stringify(sockets,null,2)} as const;\nexport const RhinoScale=.5;\nexport const ColossusScale=.88;\n`);
const report={tool:'image_gen.imagegen',generatedImage:'exec-9cd5430b-8000-462d-a429-ff92961d56bd.png',draftImage:'exec-53522353-180e-4141-8a21-e0fa7266b8d0.png',lineWeightEdit:'exec-63fd07a4-9196-4ba0-812b-6e48e626344e.png',prompt:'../素材/游戏美术/source/v101/prompt.txt',refinements:'../素材/游戏美术/source/v101/refinement-prompts.txt',operation:'redraw compact full poses; refine contour thickness and alpha using imagegen; exact RGBA crops; unchanged runtime scale .88; replaced existing atlas',atlas:{path:'assets/landart/boss-v088.png',size:[atlas.width,atlas.height],bytes:bytes.length,sha256:sha(bytes)},records};
writeFileSync('../开发进度/验证记录/v101-art.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({frames:records.length,atlasBytes:bytes.length,colossus:records.filter(r=>r.id.startsWith('colossus.')).map(r=>({id:r.id,crop:r.crop,pivot:r.pivot}))}));
