import { PNG } from "pngjs";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

// Asset preparation only: isolate complete generated sprites, preserve their
// pixels/alpha, area-resample and pack. No icon drawing, masking or recoloring.
const source = "../素材/游戏美术/source/v084/controls-comic-final.png",
  bytes = readFileSync(source);
const p = PNG.sync.read(bytes),
  visited = new Uint8Array(p.width * p.height),
  queue = new Int32Array(p.width * p.height),
  components = [];
for (let seed = 0; seed < visited.length; seed++) {
  if (visited[seed] || p.data[seed * 4 + 3] < 64) continue;
  let head = 0,
    tail = 1,
    l = p.width,
    r = 0,
    t = p.height,
    b = 0;
  queue[0] = seed;
  visited[seed] = 1;
  while (head < tail) {
    const index = queue[head++],
      x = index % p.width,
      y = Math.floor(index / p.width);
    l = Math.min(l, x);
    r = Math.max(r, x);
    t = Math.min(t, y);
    b = Math.max(b, y);
    for (const next of [
      x > 0 ? index - 1 : -1,
      x < p.width - 1 ? index + 1 : -1,
      y > 0 ? index - p.width : -1,
      y < p.height - 1 ? index + p.width : -1,
    ]) {
      if (next < 0 || visited[next] || p.data[next * 4 + 3] < 64) continue;
      visited[next] = 1;
      queue[tail++] = next;
    }
  }
  if (tail > 15000)
    components.push({
      l: Math.max(0, l - 2),
      t: Math.max(0, t - 2),
      r: Math.min(p.width - 1, r + 2),
      b: Math.min(p.height - 1, b + 2),
      pixels: tail,
    });
}
if (components.length !== 12)
  throw Error(`Expected 12 complete sprites; found ${components.length}`);
const ordered = [];
for (let row = 0; row < 3; row++) {
  const cells = components
    .filter((c) => Math.floor((c.t + c.b) / 2 / (p.height / 3)) === row)
    .sort((a, b) => a.l - b.l);
  if (cells.length !== 4) throw Error("Incorrect row " + row);
  ordered.push(...cells);
}
const ids = [
  "attack",
  "jump",
  "dash",
  "grenade",
  "knife",
  "slide",
  "pause",
  "doubleJump",
  "stickBase",
  "stickCap",
  "badge",
  "menu",
];
const atlas = new PNG({ width: 2048, height: 1024 }),
  frames = {},
  manifest = [];
let ax = 4,
  ay = 4,
  rowHeight = 0;
for (let n = 0; n < ordered.length; n++) {
  const c = ordered[n],
    sw = c.r - c.l + 1,
    sh = c.b - c.t + 1,
    scale = 300 / Math.max(sw, sh),
    w = Math.round(sw * scale),
    h = Math.round(sh * scale);
  if (ax + w + 4 > atlas.width) {
    ax = 4;
    ay += rowHeight + 8;
    rowHeight = 0;
  }
  if (ay + h + 4 > atlas.height) throw Error("Atlas overflow");
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const xa = c.l + (x * sw) / w,
        xb = c.l + ((x + 1) * sw) / w,
        ya = c.t + (y * sh) / h,
        yb = c.t + ((y + 1) * sh) / h;
      let weight = 0,
        alpha = 0,
        red = 0,
        green = 0,
        blue = 0;
      for (let sy = Math.floor(ya); sy < Math.ceil(yb); sy++)
        for (let sx = Math.floor(xa); sx < Math.ceil(xb); sx++) {
          const area =
            Math.max(0, Math.min(sx + 1, xb) - Math.max(sx, xa)) *
            Math.max(0, Math.min(sy + 1, yb) - Math.max(sy, ya));
          const i = (sy * p.width + sx) * 4,
            a = p.data[i + 3] * area;
          weight += area;
          alpha += a;
          red += p.data[i] * a;
          green += p.data[i + 1] * a;
          blue += p.data[i + 2] * a;
        }
      const i = ((ay + y) * atlas.width + ax + x) * 4;
      atlas.data[i] = alpha ? red / alpha : 0;
      atlas.data[i + 1] = alpha ? green / alpha : 0;
      atlas.data[i + 2] = alpha ? blue / alpha : 0;
      atlas.data[i + 3] = alpha / weight;
    }
  frames[ids[n]] = { rect: [ax, ay, w, h], size: [w, h] };
  manifest.push({
    id: ids[n],
    crop: [c.l, c.t, sw, sh],
    atlas: [ax, ay, w, h],
    sourcePixels: c.pixels,
  });
  ax += w + 8;
  rowHeight = Math.max(rowHeight, h);
}
const output = "assets/landart/controls.png";
writeFileSync(output, PNG.sync.write(atlas));
const sha = (b) => createHash("sha256").update(b).digest("hex");
writeFileSync(
  "assets/scripts/ui/ControlFrames.ts",
  "// Generated by scripts/pack-v084-controls.mjs from imagegen art.\nexport const ControlFrames = " +
    JSON.stringify(frames) +
    " as const;\nexport type ControlFrameId = keyof typeof ControlFrames;\n",
);
writeFileSync(
  "../素材/游戏美术/v084-controls-manifest.json",
  JSON.stringify(
    {
      source,
      sourceSize: [p.width, p.height],
      sourceSHA256: sha(bytes),
      atlas: output,
      atlasSize: [atlas.width, atlas.height],
      atlasSHA256: sha(readFileSync(output)),
      preparation:
        "Whole sprites; alpha-preserving crop, area resampling and packing only. No drawn substitutes.",
      frames: manifest,
    },
    null,
    2,
  ),
);
console.log({
  sprites: manifest.length,
  sourceSize: [p.width, p.height],
  atlasSize: [atlas.width, atlas.height],
  usedHeight: ay + rowHeight,
  bytes: readFileSync(output).length,
});
