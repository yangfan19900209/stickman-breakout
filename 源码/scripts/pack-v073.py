from os.path import relpath
"""Deterministic cropping/packing of generated sources. No painted edits or erased body parts."""
from pathlib import Path
from PIL import Image
import json, hashlib, math
ROOT=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
frames={}; records=[]
def crop(name, ident, box, factor=.5):
    src=ROOT/'../素材/游戏美术/source/v073'/f'{name}.png';im=Image.open(src).convert('RGBA')
    cell=im.crop(box);bbox=cell.getchannel('A').point(lambda a:255 if a>30 else 0).getbbox()
    assert bbox,ident
    region=cell.crop(bbox);dest=ROOT/'../素材/游戏美术/slices/v073'/f'{ident}.png';region.save(dest)
    size=region.size;runtime=region.resize((round(size[0]*factor),round(size[1]*factor)),Image.Resampling.LANCZOS)
    out=ROOT/'assets/level02'/f'{ident}.png';runtime.quantize(colors=192,method=Image.Quantize.FASTOCTREE).save(out,optimize=True)
    frame={'file':ident,'size':list(runtime.size),'sourceSize':list(size),'source':str(Path(relpath(dest, ROOT))).replace('\\','/'),'sha256':sha(out)}
    frames[ident]=frame
    records.append({'id':ident,'sheet':str(Path(relpath(src, ROOT))).replace('\\','/'),'sheetSHA256':sha(src),'sourceSHA256':sha(dest),'cell':box,'crop':[box[0]+bbox[0],box[1]+bbox[1],*size],**frame})
    return region
terrain=[('seabed',[0,0,754,380]),('pillar',[754,0,1448,380]),('ceiling',[0,395,688,712]),('deck',[688,395,1448,712]),('bulkhead',[0,712,665,1086]),('pump',[665,712,1448,1086])]
for name,box in terrain:crop('terrain','reef.'+name,box,1)
hero_boxes=[[0,0,512,512],[512,0,950,512],[950,0,1536,512],[0,512,512,1024],[512,512,943,1024],[943,512,1536,1024]]
for name,box in zip(['hover.0','hover.1','swim.0','swim.1','fire','boost'],hero_boxes):
    crop('harpoon','diver.harpoon.'+name,box,.6)
im=Image.open(ROOT/'../素材/游戏美术/source/v073/effects.png');w,h=im.size
for i in range(8):
    x=round(i%4*w/4);y=round(i//4*h/2)
    box=[[0,0,400,443],[410,0,804,443],[800,0,1300,443],[1300,0,1774,443]][i] if i<4 else [x,y,round(x+w/4),round(y+h/2)]
    crop('effects',f'fx.burst.{i}',box,.6)
# The rail/spear region is cropped from the complete holding pose; no redraw/masking.
crop('harpoon','item.harpoon',[712,726,944,791],.65)
crop('harpoon','projectile.harpoon',[868,730,944,760],1)
out=ROOT/'assets/scripts/ocean/OceanDetailFrames.ts'
out.write_text('// Generated by scripts/pack-v073.py.\nexport const OceanDetailFrames = '+json.dumps(frames,separators=(',',':'))+';\n',encoding='utf-8')
# Current collision profiles are generated by pack-v075.py (OceanStyleArt).
(ROOT/'../素材/游戏美术/v073-manifest.json').write_text(json.dumps({'processing':'Cell crop with original alpha preserved; runtime resize and 192-color palette quantization (lossy); originals unchanged','frames':records},indent=2),encoding='utf-8')
for f in records:print(f['id'],f['crop'],f['sourceSize'])
