from os.path import relpath
"""Pack complete upward-aim poses; preserve the generated original and record sockets."""
from pathlib import Path
import hashlib
import json
import math
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '../素材/游戏美术/source/v065/rocket-aim.png'
OUT = ROOT / '../素材/游戏美术/slices/v065'
OUT.mkdir(parents=True, exist_ok=True)
sheet = Image.open(SOURCE).convert('RGBA')
assert sheet.size == (1774, 887), 'Re-measure the sprite cells and sockets if the source changes.'
WORLD_SCALE = .25
# Name, column, row, virtual foot pivot, muzzle center, rear exhaust center.
poses = [
    ('up-stand', 0, 0, (214, 407), (284, 46), (284, 267)),
    ('up-crouch', 1, 0, (650, 407), (722, 89), (722, 305)),
    ('up-jump', 2, 0, (1082, 407), (1156, 33), (1156, 242)),
    ('up-fall', 3, 0, (1535, 407), (1600, 33), (1600, 244)),
    ('diagonal-run.0', 0, 1, (214, 844), (337, 563), (197, 703)),
    ('diagonal-run.1', 1, 1, (650, 844), (782, 563), (642, 703)),
    ('diagonal-crouch', 2, 1, (1082, 837), (1227, 582), (1087, 722)),
    ('diagonal-air', 3, 1, (1535, 844), (1663, 540), (1523, 680)),
]
frames, barrels, clips, entries = {}, {}, {}, []
atlas = Image.new('RGBA', (1024, 512))
x, y, row_height = 4, 4, 0
for name, col, row, pivot, muzzle, rear in poses:
    cell = (round(sheet.width * col / 4), round(sheet.height * row / 2),
            round(sheet.width * (col + 1) / 4), round(sheet.height * (row + 1) / 2))
    # Ignore almost invisible alpha speckle only when deciding the outer crop;
    # all source pixels within the selected complete-body rectangle are retained.
    bbox = sheet.crop(cell).getchannel('A').point(lambda value: 255 if value >= 64 else 0).getbbox()
    assert bbox
    left = max(cell[0], (cell[0] + bbox[0] - 4) // 2 * 2)
    top = max(cell[1], (cell[1] + bbox[1] - 4) // 2 * 2)
    right = min(cell[2], math.ceil((cell[0] + bbox[2] + 4) / 2) * 2)
    bottom = min(cell[3], math.ceil((cell[1] + bbox[3] + 4) / 2) * 2)
    crop = (left, top, right, bottom)
    original = sheet.crop(crop)
    image = original.resize((original.width // 2, original.height // 2), Image.Resampling.LANCZOS)
    frame_id = 'direct.rocket.' + name
    original.save(OUT / (frame_id + '.png'), optimize=True)
    if x + image.width + 4 > atlas.width:
        x, y, row_height = 4, y + row_height + 8, 0
    assert y + image.height + 4 <= atlas.height
    atlas.paste(image, (x, y))
    # Two-pixel extrusion protects edges when the small sprites are sampled linearly.
    for box, size, point in [((0, 0, image.width, 1), (image.width, 2), (x, y - 2)),
                             ((0, image.height - 1, image.width, image.height), (image.width, 2), (x, y + image.height)),
                             ((0, 0, 1, image.height), (2, image.height), (x - 2, y)),
                             ((image.width - 1, 0, image.width, image.height), (2, image.height), (x + image.width, y))]:
        atlas.paste(image.crop(box).resize(size, Image.Resampling.NEAREST), point)
    anchor = [(pivot[0] - left) / original.width, 1 - (pivot[1] - top) / original.height]
    frames[frame_id] = dict(atlas=[x, y, *image.size], anchor=anchor,
                            sourceSize=list(original.size), size=list(image.size))
    barrels[frame_id] = dict(x=(muzzle[0] - pivot[0]) * WORLD_SCALE,
                             y=(pivot[1] - muzzle[1]) * WORLD_SCALE,
                             backX=(rear[0] - pivot[0]) * WORLD_SCALE,
                             backY=(pivot[1] - rear[1]) * WORLD_SCALE,
                             pitch=math.atan2(rear[1] - muzzle[1], muzzle[0] - rear[0]))
    clip = 'rocket.' + name.split('.')[0]
    clips.setdefault(clip, []).append(frame_id)
    entries.append(dict(id=frame_id, crop=list(crop), pivotSource=list(pivot),
                        muzzleSource=list(muzzle), rearSource=list(rear), **frames[frame_id]))
    x += image.width + 8
    row_height = max(row_height, image.height)
runtime = ROOT / 'assets/resources/comic/rocket-aim.png'
atlas.quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(runtime, optimize=True)
output = '// Generated by scripts/prepare-rocket-aim.py from whole upward-aim poses.\n'
for name, data in [('RocketAimFrames', frames), ('RocketAimBarrels', barrels), ('RocketAimClips', clips)]:
    output += 'export const ' + name + ' = ' + json.dumps(data, separators=(',', ':')) + ' as const;\n'
output += 'export const RocketAimScale = .25;\n'
(ROOT / 'assets/scripts/render/RocketAimFrames.ts').write_text(output, encoding='utf-8')
manifest = dict(source=dict(file=Path(relpath(SOURCE, ROOT)).as_posix(), size=list(sheet.size),
                            sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest()),
                textureSize=list(atlas.size), textureBytes=runtime.stat().st_size, worldScale=WORLD_SCALE,
                processing='Complete-body crops, uniform half-resolution runtime frames, 128-color RGBA quantization; original preserved.',
                frames=entries)
(ROOT / '../素材/游戏美术/v065-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(dict(frames=len(entries), atlas=list(atlas.size), bytes=runtime.stat().st_size)))
