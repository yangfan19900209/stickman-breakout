import {PNG} from 'pngjs';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const atlas=new PNG({width:1024,height:1024}), frames={}, rockets={}, sockets={}, entries=[];
const input=name=>PNG.sync.read(readFileSync(`../素材/游戏美术/source/v080/${name}.png`));
function cut(p,region){
 let [x,y,w,h]=region,left=x+w,top=y+h,right=x,bottom=y;
 for(let yy=y;yy<y+h;yy++)for(let xx=x;xx<x+w;xx++)if(p.data[(yy*p.width+xx)*4+3]>16){left=Math.min(left,xx);top=Math.min(top,yy);right=Math.max(right,xx);bottom=Math.max(bottom,yy);}
 return [Math.max(x,left-2),Math.max(y,top-2),Math.min(x+w-1,right+2),Math.min(y+h-1,bottom+2)];
}
function put(id,p,region,dx,dy,target,actor=false,hip=0,muzzleY=0){
 const [left,top,right,bottom]=cut(p,region),sw=right-left+1,sh=bottom-top+1;
 const ratio=actor?.31:Math.min(target[0]/sw,target[1]/sh),w=Math.ceil(sw*ratio),h=Math.ceil(sh*ratio);
 // Area sampling with premultiplied alpha preserves the generated silhouette.
 for(let y=0;y<h;y++)for(let x=0;x<w;x++){
  const x0=left+x/ratio,x1=Math.min(right+1,left+(x+1)/ratio),y0=top+y/ratio,y1=Math.min(bottom+1,top+(y+1)/ratio);
  let r=0,g=0,b=0,a=0,weight=0;
  for(let yy=Math.floor(y0);yy<Math.ceil(y1);yy++)for(let xx=Math.floor(x0);xx<Math.ceil(x1);xx++){
   const q=Math.max(0,Math.min(xx+1,x1)-Math.max(xx,x0))*Math.max(0,Math.min(yy+1,y1)-Math.max(yy,y0)),at=(yy*p.width+xx)*4,alpha=p.data[at+3]*q;
   a+=alpha;weight+=q;r+=p.data[at]*alpha;g+=p.data[at+1]*alpha;b+=p.data[at+2]*alpha;
  }
  const at=((dy+y)*atlas.width+dx+x)*4;atlas.data[at]=a?r/a:0;atlas.data[at+1]=a?g/a:0;atlas.data[at+2]=a?b/a:0;atlas.data[at+3]=weight?a/weight:0;
 }
 const anchor=actor?[(hip-left)*ratio/w,2*ratio/h]:[.5,0];
 const data={atlas:[dx,dy,w,h],size:[w,h],sourceSize:[w,h],anchor};
 (actor?rockets:frames)[id]=data;
 if(actor)sockets[id]=[(right-15-hip)*ratio*.84,(bottom-2-muzzleY)*ratio*.84];
 entries.push({id,sourceCrop:[left,top,sw,sh],...data});
}
const walk=input('rocket-walk');
for(let i=0;i<8;i++)put(`direct.rocket.stride.${i}`,walk,[(i%4)*384,Math.floor(i/4)*512,384,512],4+(i%4)*128,4+Math.floor(i/4)*112,[120,100],true,(i%4)*384+166,Math.floor(i/4)*512+213);
const scenery=input('base-scenery');
for(const [i,id] of ['bunker','tower','factory','tent'].entries()){
 const top=i<2?0:580,height=i<2?580:444;
 put(`polish.${id}`,scenery,[(i%2)*768,top,768,height],4+(i%2)*504,236+Math.floor(i/2)*272,[480,254]);
}
const props=input('supplies'),pw=props.width/2,ph=props.height/2;
for(const [i,id] of ['crate','barrel','ammo','grenades'].entries())
 put(`polish.${id}`,props,[(i%2)*pw,Math.floor(i/2)*ph,pw,ph],4+i*160,800,[144,144]);
mkdirSync('assets/landart',{recursive:true});
writeFileSync('assets/landart/polish.png',PNG.sync.write(atlas));
writeFileSync('assets/scripts/render/LandPolishFrames.ts','// Generated by scripts/pack-v080-art.mjs; alpha retained.\nexport const LandPolishFrames = '+JSON.stringify(frames)+' as const;\n');
writeFileSync('assets/scripts/render/RocketWalkFrames.ts','// Generated by scripts/pack-v080-art.mjs; whole equipped gait poses.\nexport const RocketWalkFrames = '+JSON.stringify(rockets)+' as const;\nexport const RocketWalkSockets = '+JSON.stringify(sockets)+' as const;\nexport const RocketWalkCycle = '+JSON.stringify([0,1,2,4,5,6].map(i=>`direct.rocket.stride.${i}`))+' as const;\n');
writeFileSync('../素材/游戏美术/v080-art-manifest.json',JSON.stringify({sources:['rocket-walk','base-scenery','supplies'].map(n=>({path:`../素材/游戏美术/source/v080/${n}.png`,sha256:createHash('sha256').update(readFileSync(`../素材/游戏美术/source/v080/${n}.png`)).digest('hex')})),runtime:'assets/landart/polish.png',size:[1024,1024],frames:entries},null,2));
console.log(JSON.stringify(entries.map(e=>({id:e.id,size:e.size,anchor:e.anchor})),null,2));
