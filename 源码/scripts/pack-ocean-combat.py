from os.path import relpath
"""Pixel-preserving combat atlas. Keep art/ and original runtime textures intact.
Run npm test (transpile), then export OceanFrames to reports/v077-ocean-pack-input.json.
"""
import json, hashlib, uuid
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'../开发进度/验证记录/v077-ocean-pack-input.json').read_text(encoding='utf8'))
frames=[(key,value) for key,value in data.items() if key.startswith(('diver.','enemy.','fx.','projectile.'))]
frames.sort(key=lambda item:(-item[1]['size'][1],item[0]))
width=2048; padding=3; x=y=row=0; placements=[]
for key,f in frames:
    source=ROOT/'assets/level02'/f"{f['file']}.png"
    im=Image.open(source).convert('RGBA');w,h=im.size
    if x+w+padding*2>width:x=0;y+=row;row=0
    placements.append((key,source,im,(x+padding,y+padding,w,h)))
    x+=w+padding*2;row=max(row,h+padding*2)
height=((y+row+3)//4)*4
assert height<=2048,(width,height)
atlas=Image.new('RGBA',(width,height));rects={};manifest=[]
for key,source,im,rect in placements:
    x,y,w,h=rect
    # Extrude all four edges and corners for linear filtering at small scales.
    for ox in range(-2,3):
        for oy in range(-2,3):atlas.paste(im,(x+ox,y+oy))
    atlas.paste(im,(x,y))
    assert atlas.crop((x,y,x+w,y+h)).tobytes()==im.tobytes()
    rects[key]=list(rect)
    manifest.append({'id':key,'runtimeSource':Path(relpath(source, ROOT)).as_posix(),'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'atlas':list(rect),'pixelsIdentical':True})
dest=ROOT/'assets/level02/combat-atlas.png';atlas.save(dest,optimize=True)
# Use the existing texture import contract, with stable dedicated UUIDs.
meta=json.loads((ROOT/'assets/level02/enemy.diver.swim.png.meta').read_text(encoding='utf8'))
uid=str(uuid.uuid5(uuid.NAMESPACE_URL,'stickman/level02/combat-atlas-v077'))
meta['uuid']=uid;meta['userData']['redirect']=uid+'@6c48a'
sub=meta['subMetas']['6c48a'];sub['uuid']=uid+'@6c48a';sub['displayName']='combat-atlas';sub['userData']['imageUuidOrDatabaseUri']=uid
sub['userData']['wrapModeS']=sub['userData']['wrapModeT']='clamp-to-edge'
Path(str(dest)+'.meta').write_text(json.dumps(meta,indent=2),encoding='utf8')
(ROOT/'assets/scripts/ocean/OceanCombatAtlas.ts').write_text('// Generated by scripts/pack-ocean-combat.py; original pixels and logical sizes unchanged.\nexport const OceanCombatAtlas: Record<string, readonly [number,number,number,number]> = '+json.dumps(rects,separators=(',',':'))+';\n',encoding='utf8')
report={'processing':'RGBA pixel-preserving packing, 3px gutter, 2px edge extrusion, no resizing or quantization','texture':Path(relpath(dest, ROOT)).as_posix(),'size':[width,height],'sha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'frames':manifest}
(ROOT/'../素材/游戏美术/v077-combat-atlas.json').write_text(json.dumps(report,indent=2),encoding='utf8')
print(json.dumps({'frames':len(frames),'size':[width,height],'bytes':dest.stat().st_size,'pixelsIdentical':True}))
