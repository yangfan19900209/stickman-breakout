import { PNG } from 'pngjs';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Crop complete generated poses and pack unchanged RGBA pixels. No repainted limbs.
const sha=b=>createHash('sha256').update(b).digest('hex');
const specs=[
  {file:'rhino',rows:2,names:['idle','roll.0','roll.1','fire','ram-tell','ram','damaged','wreck'],
    pivots:[[245,391],[689,391],[1133,392],[1576,391],[245,836],[690,836],[1133,835],[1576,835]],
    sockets:[[79,221],[524,222],[968,226],[1447,228],[93,632],[500,693],[964,667],[1400,730]].map(muzzle=>({muzzle}))},
  {file:'colossus',rows:3,names:['idle','walk.0','walk.1','walk.2','walk.3','fire','stomp-tell','stomp','charge','damaged','collapse','wreck'],
    pivots:[[220,327],[567,327],[927,327],[1270,327],[202,691],[550,691],[920,691],[1263,691],[220,1047],[562,1047],[903,1047],[1239,1047]],
    sockets:[[[44,189],[220,147],[145,92],[305,99]],[[408,184],[570,145],[500,96],[654,96]],[[764,185],[920,147],[847,92],[992,83]],[[1110,187],[1270,147],[1207,99],[1352,105]],[[34,545],[198,508],[132,450],[284,450]],[[401,525],[571,514],[540,441],[680,482]],[[751,505],[918,497],[861,444],[993,445]],[[1094,554],[1264,548],[1180,493],[1360,489]],[[25,865],[233,867],[141,819],[302,819]],[[398,911],[566,865],[497,810],[646,810]],[[733,961],[880,917],[815,880],[943,846]],[[1080,1017],[1211,989],[1132,949],[1297,909]]].map(a=>Object.fromEntries(['muzzle','core','leftPod','rightPod'].map((k,i)=>[k,a[i]])))}
];
const records=[], atlas=new PNG({width:2048,height:2048}), frames={}, sockets={};
let ax=4,ay=4,rowH=0;
function cropBox(p,l,t,r,b){
  let left=r,top=b,right=l,bottom=t,pixels=0,white=0;
  for(let y=t;y<b;y++)for(let x=l;x<r;x++){const i=(y*p.width+x)*4;if(p.data[i+3]<=20)continue;
    left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);pixels++;
    if(p.data[i]>220&&p.data[i+3]>245)white++;
  }
  if(pixels<1000||white<500)throw Error('Empty/transparent interior');
  return {box:[Math.max(l,left-3),Math.max(t,top-3),Math.min(r,right+4),Math.min(b,bottom+4)],pixels,white};
}
function pack(target,p,box,id,pivot,map){
  const [l,t,r,b]=box,w=r-l,h=b-t;
  if(ax+w+4>target.width){ax=4;ay+=rowH+8;rowH=0;}
  if(ay+h+4>target.height)throw Error('Atlas overflow');
  for(let y=0;y<h;y++)p.data.copy(target.data,((ay+y)*target.width+ax)*4,((t+y)*p.width+l)*4,((t+y)*p.width+r)*4);
  const result={atlas:[ax,ay,w,h],size:[w,h],sourceSize:[w,h],anchor:pivot?[(pivot[0]-l)/w,1-(pivot[1]-t)/h]:[0,0]};
  if(map)sockets[id]=Object.fromEntries(Object.entries(map).map(([k,[x,y]])=>[k,[x-pivot[0],pivot[1]-y]]));
  ax+=w+8;rowH=Math.max(rowH,h);return result;
}
for(const spec of specs){
  const bytes=readFileSync(`../素材/游戏美术/source/v088/${spec.file}.png`),p=PNG.sync.read(bytes);
  for(let row=0;row<spec.rows;row++){
    const top=Math.floor(row*p.height/spec.rows),bottom=Math.floor((row+1)*p.height/spec.rows),runs=[];
    let start=-1;
    for(let x=0;x<=p.width;x++){
      let count=0;if(x<p.width)for(let y=top;y<bottom;y++)if(p.data[(y*p.width+x)*4+3]>20)count++;
      if(count>1){if(start<0)start=x;}else if(start>=0){if(x-start>40)runs.push([start,x]);start=-1;}
    }
    if(runs.length!==4)throw Error(`Expected 4 isolated poses: ${spec.file}/${row}: ${JSON.stringify(runs)}`);
    for(let col=0;col<4;col++){
      const n=row*4+col,id=`${spec.file}.${spec.names[n]}`,[l,r]=runs[col],crop=cropBox(p,Math.max(0,l-3),top,Math.min(p.width,r+3),bottom);
      frames[id]=pack(atlas,p,crop.box,id,spec.pivots[n],spec.sockets[n]);
      records.push({id,source:`../素材/游戏美术/source/v088/${spec.file}.png`,sourceSHA256:sha(bytes),crop:crop.box,region:frames[id].atlas,opaqueWhite:crop.white,pixels:crop.pixels});
    }
  }
}
const bossBytes=PNG.sync.write(atlas);writeFileSync('assets/landart/boss-v088.png',bossBytes);
writeFileSync('assets/scripts/render/BossFrames.ts',`// Generated by scripts/pack-v088-art.mjs. Sockets are source pixels relative to measured foot pivots.\nexport const BossFrames=${JSON.stringify(frames,null,2)} as const;\nexport const BossSockets=${JSON.stringify(sockets,null,2)} as const;\nexport const RhinoScale=.5;\nexport const ColossusScale=.88;\n`);

const terrainBytes=readFileSync('../素材/游戏美术/source/v088/terrain.png'),terrain=PNG.sync.read(terrainBytes),terrainAtlas=new PNG({width:2048,height:1024}),terrainFrames={};
ax=ay=4;rowH=0;
for(const [name,l,t,r,b] of [['deck.rib',65,70,1470,280],['deck.panel',65,320,1470,530],['grass',52,637,1482,758],['concrete',52,851,1482,969]]){
  const id=`terrain088.${name}`,crop=name.startsWith('deck')?cropBox(terrain,l,t,r,b):{box:[l,t,r,b]};
  terrainFrames[id]=pack(terrainAtlas,terrain,crop.box,id);
  // Linear filtering at a mirrored tile boundary must sample the same edge
  // colour, not the transparent atlas gutter. Keep every source pixel intact.
  const [gx,gy,gw,gh]=terrainFrames[id].atlas;
  for(let py=-2;py<gh+2;py++)for(let px=-2;px<gw+2;px++){
    if(px>=0&&px<gw&&py>=0&&py<gh)continue;
    const sx=gx+Math.max(0,Math.min(gw-1,px)),sy=gy+Math.max(0,Math.min(gh-1,py));
    const source=(sy*terrainAtlas.width+sx)*4,target=((gy+py)*terrainAtlas.width+gx+px)*4;
    terrainAtlas.data.copy(terrainAtlas.data,target,source,source+4);
  }
  records.push({id,source:'../素材/游戏美术/source/v088/terrain.png',sourceSHA256:sha(terrainBytes),crop:crop.box,region:terrainFrames[id].atlas});
}
const tb=PNG.sync.write(terrainAtlas);writeFileSync('assets/landart/terrain-v088.png',tb);
writeFileSync('assets/scripts/render/TerrainV088Frames.ts',`// Complete generated beams and quiet surface strips, without per-tile end caps.\nexport const TerrainV088Frames=${JSON.stringify(terrainFrames,null,2)} as const;\n`);
for(const name of ['boss-v088','terrain-v088']){
  const template=readFileSync('assets/landart/soil.png.meta','utf8'),h=sha(name).slice(0,32),uuid=`${h.slice(0,8)}-${h.slice(8,12)}-${h.slice(12,16)}-${h.slice(16,20)}-${h.slice(20)}`;
  writeFileSync(`assets/landart/${name}.png.meta`,template.replaceAll('2c3e798f-728b-400c-befb-bc1c173c841c',uuid).replaceAll('"soil"',`"${name}"`).replaceAll('"repeat"','"clamp-to-edge"'));
}
