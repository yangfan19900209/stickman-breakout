import {PNG} from 'pngjs';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

// Whole generated silhouettes only. Area resampling preserves opaque white
// costume fills; each sheet uses ONE identity scale, not per-pose stretching.
const atlas=new PNG({width:1024,height:1024}), frames={},sockets={},barrels={},cuts=[],sources=[];
let px=4,py=4,rh=0;
function sheet(name,cols,rows,scale,tips,backs,hips){
  const file=`../素材/游戏美术/source/v083/${name}.png`,bytes=readFileSync(file),p=PNG.sync.read(bytes);
  if(p.width!==1254||p.height!==1254)throw Error('Re-measure sockets for changed source dimensions');
  // Inspection preview uses 1280 units. Convert measured points to actual pixels.
  const unit=p.width/1280;scale/=unit;
  tips=tips.map(v=>v?.map(n=>n*unit));backs=backs.map(v=>v?.map(n=>n*unit));hips=hips.map(n=>n*unit);
  sources.push({file,size:[p.width,p.height],sha256:createHash('sha256').update(bytes).digest('hex')});
  for(let row=0;row<rows;row++)for(let col=0;col<cols;col++){
    const index=row*cols+col,x0=Math.floor(col*p.width/cols),x1=Math.floor((col+1)*p.width/cols),
      y0=Math.floor(row*p.height/rows),y1=Math.floor((row+1)*p.height/rows);
    let l=x1,t=y1,r=x0,b=y0,active=0;
    for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++)if(p.data[(y*p.width+x)*4+3]>32){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);active++;}
    if(active<100||l<=x0||r>=x1-1||t<=y0||b>=y1-1)throw Error(`Clipped/empty frame ${name}.${index}`);
    l-=2;t-=2;r+=2;const sole=b;b+=2;
    const sw=r-l+1,sh=b-t+1,ratio=scale*2,w=Math.ceil(sw*ratio),h=Math.ceil(sh*ratio);
    if(px+w+4>atlas.width){px=4;py+=rh+8;rh=0;}if(py+h+4>atlas.height)throw Error('Atlas full');
    for(let y=0;y<h;y++)for(let x=0;x<w;x++){
      const xa=l+x/ratio,xb=Math.min(r+1,l+(x+1)/ratio),ya=t+y/ratio,yb=Math.min(b+1,t+(y+1)/ratio);
      let a=0,rr=0,g=0,bb=0,sum=0;
      for(let sy=Math.floor(ya);sy<Math.ceil(yb);sy++)for(let sx=Math.floor(xa);sx<Math.ceil(xb);sx++){
        const q=Math.max(0,Math.min(sx+1,xb)-Math.max(sx,xa))*Math.max(0,Math.min(sy+1,yb)-Math.max(sy,ya)),i=(sy*p.width+sx)*4,v=p.data[i+3]*q;
        a+=v;sum+=q;rr+=p.data[i]*v;g+=p.data[i+1]*v;bb+=p.data[i+2]*v;
      }
      const i=((py+y)*atlas.width+px+x)*4;atlas.data[i]=a?rr/a:0;atlas.data[i+1]=a?g/a:0;atlas.data[i+2]=a?bb/a:0;atlas.data[i+3]=sum?a/sum:0;
    }
    const family=name==='aim-walk'?(row<2?'rifle':'rocket'):['rifle','rocket','knife'][row];
    const action=name==='aim-walk'?(row%2?'up-walk':'diagonal-walk'):'slide';
    const id=`direct.${family}.${action}.${col}`,hip=hips[index],anchor=[(hip-l)/sw,(b+1-sole)/sh];
    const data={atlas:[px,py,w,h],size:[w,h],sourceSize:[sw*scale/.84,sh*scale/.84],anchor};frames[id]=data;
    if(tips[index]){
      const [tx,ty]=tips[index];sockets[id]=[(tx-hip)*scale,(sole-ty)*scale];
      if(family==='rocket'){
        const [bx,by]=backs[index];barrels[id]={x:sockets[id][0],y:sockets[id][1],backX:(bx-hip)*scale,backY:(sole-by)*scale,pitch:Math.atan2(by-ty,tx-bx)};
      }
    }
    cuts.push({id,source:file,index,crop:[l,t,sw,sh],atlas:data.atlas,anchor,worldSize:[sw*scale,sh*scale],scale,sole,hip,muzzle:tips[index]??null,rear:backs[index]??null});
    px+=w+8;rh=Math.max(rh,h);
  }
}
